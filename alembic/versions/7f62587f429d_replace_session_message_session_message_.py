        if migrated_msg_id is None:
            continue
        new_channel_id = conn.execute(
            sa.select(msg_table.c.channel_id).where(msg_table.c.id == migrated_msg_id)
        ).scalar_one()
        conn.execute(
            sa.insert(read_table).values(
                channel_id=new_channel_id,
                session_id=row.session_id,
                read_at=_parse_dt(row.created_at),
                up_to_message_id=migrated_msg_id,
                created_at=now,
                updated_at=now,
            )
        )


