    def _insert_returning_id(table: sa.TableClause, **values: Any) -> int:
        conn.execute(sa.insert(table).values(**values))
        new_id = conn.execute(sa.text("SELECT last_insert_rowid()")).scalar_one()
        assert isinstance(new_id, int)
        return new_id

